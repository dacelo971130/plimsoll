def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value * 100:.0f}%"


def _frac(num: int, den: int) -> str:
    return "—" if not den else f"{num}/{den}"


def summary_cells(s: ToolScore) -> dict[str, str]:
    cards = _ratio(s.on_scored, s.detected)
    return {
        "高風險漏報": str(len(s.missed_high)),
        "回報筆數": str(s.reported),
        "偵測率": f"{_pct(_ratio(s.detected, s.scored_total))}（{_frac(s.detected, s.scored_total)}）",
        "高風險偵測率": f"{_pct(_ratio(s.high_detected, s.high_total))}（{_frac(s.high_detected, s.high_total)}）",
        "精確率": _pct(precision(s)) + (
            f"（只計 {s.precision_base} 筆）" if s.precision_base and s.precision_base != s.reported else ""
        ),
        "雜訊筆數": "—" if s.recall_only else str(len(s.noise)),
        "每筆變更卡片數": "—" if cards is None else f"{cards:.1f}",
        "風險一致率": _pct(_ratio(s.risk_agree, s.risk_known)) if s.risk_graded else "不分級",
        "高風險被低估": str(len(s.high_underrated)) if s.risk_graded else "—",
        "過度警示": str(len(s.over_rated)) if s.risk_graded else "—",
        "頁碼正確": _pct(_ratio(s.page_ok, s.page_known)),
        "類型正確": _pct(_ratio(s.type_ok, s.type_known)),
    }


def print_terminal(per_case: list[tuple[Case, list[ToolScore]]], totals: list[ToolScore]) -> None:
    for case, scores in per_case:
        print(f"\n■ {case.title}（{case.id}）")
        if case.home_field:
            print("  ⚠ 主場文件：只能驗證評分工具，不能當對外準確率")
        for s in scores:
            cells = summary_cells(s)
            print(f"  {s.tool:<12} " + "  ".join(f"{k} {v}" for k, v in cells.items()))
            if s.missed_high:
                print(f"  {'':<12} 漏掉的高風險：{', '.join(s.missed_high)}")
            pending = [r for r in s.noise if on_answer_pages(r, case)] if s.recall_only else s.noise
            if pending:
                rows = ", ".join(f"第{r.row}行" for r in pending[:8]) + ("…" if len(pending) > 8 else "")
                label = "落在答案頁碼上但沒對到錨點" if s.recall_only else "未對應（雜訊或待人工 gt_id）"
                print(f"  {'':<12} {label}：{rows}")
    if len(per_case) > 1:
        print("\n■ 全部案例合計")
        for s in totals:
            print(f"  {s.tool:<12} " + "  ".join(f"{k} {v}" for k, v in summary_cells(s).items()))


