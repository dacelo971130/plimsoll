        elapsed = time.perf_counter() - started
        session_dir = store / "sessions" / response["session"]["session_id"]
        session = json.loads((session_dir / "session.json").read_text(encoding="utf-8"))
        differences = json.loads((session_dir / "differences.json").read_text(encoding="utf-8"))

        out = args.root / "results" / case.id / f"{OURS}.csv"
        rows = plimsoll_rows(differences)
