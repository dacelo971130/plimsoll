def load_registry(root: Path) -> list[dict]:
    """<root>/competitors.json: every product the benchmark intends to cover,
    whether or not anyone has run it yet — so the report can show coverage,
    not just the tools that happen to have a CSV."""
    path = root / "competitors.json"
    if not path.exists():
        return []
    products = json.loads(path.read_text(encoding="utf-8"))["products"]
    tools = [p["tool"] for p in products]
    if len(tools) != len(set(tools)) or OURS in tools:
        raise SystemExit(f"{path}：tool 代號重複，或用了保留給本系統的 {OURS}")
    return products


def cmd_scaffold(args) -> None:
    registry = {p["tool"]: p for p in load_registry(args.root)}
    tools = list(registry) if args.all else [args.tool]
    if not tools:
        raise SystemExit("competitors.json 裡沒有任何產品")
    templates = args.root / "templates"
    for tool in tools:
        if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", tool):
            raise SystemExit(f"工具代號「{tool}」只能用小寫英數、- 和 _（會變成檔名）")
        product = registry.get(tool, {})
        for case in discover(args.root, args.case):
            target = args.root / "results" / case.id / f"{tool}.csv"
            if target.exists():
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(templates / "result_template.csv", target)
            meta = json.loads((templates / "meta_template.json").read_text(encoding="utf-8"))
            meta["tool"] = tool
            if product:
                meta["display_name"] = product["name"]
                meta["data_handling"] = product.get("data_handling", meta["data_handling"])
                meta["settings"] = product.get("how_to_run", meta["settings"])
                meta["risk_mapping"] = product.get("risk_grading", meta["risk_mapping"])
            target.with_suffix(".json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            print(f"已建立 {target.relative_to(args.root)}")


