# ── answer key ───────────────────────────────────────────────────────────


@dataclass(frozen=True)
class TruthItem:
    id: str
    summary: str
    change_type: str
    old_pages: tuple[int, ...]
    new_pages: tuple[int, ...]
    old_anchors: tuple[str, ...]
    new_anchors: tuple[str, ...]
    expected_risk: str
    scored: bool
    risk_rationale: str = ""
    scored_note: str = ""
    # A revised table/clause may legitimately be reported as line-level
    # 刪除/新增 (a row removed, a sentence inserted). Empty = (change_type,).
    accept_change_types: tuple[str, ...] = ()

    @property
    def accepted_types(self) -> tuple[str, ...]:
        return self.accept_change_types or (self.change_type,)


@dataclass(frozen=True)
class Case:
    id: str
    title: str
    old_pdf: str
    new_pdf: str
    items: tuple[TruthItem, ...]
    old_pages_spec: str | None = None  # "7-184": compare an extract of the source, not all of it
    new_pages_spec: str | None = None
    page_tolerance: int = 0
    old_version: str | None = None
    new_version: str | None = None
    ground_truth_source: str = ""
    label_status: str = "draft"
    labeled_by: str = ""
    home_field: bool = False
    recall_only: bool = False
    notes: str = ""


def _pages(raw) -> tuple[int, ...]:
    """[3, "10-12"] → (3, 10, 11, 12): a range string keeps a clause that
    spans many pages (an official amendment list, say) writable by hand."""
    out: list[int] = []
    for value in raw or []:
        if isinstance(value, int):
            out.append(value)
            continue
        start, _, end = str(value).partition("-")
        out.extend(range(int(start), int(end or start) + 1))
    return tuple(out)


def _page_ranges(spec: str) -> list[tuple[int, int]]:
    out = []
    for part in spec.split(","):
        start, _, end = part.strip().partition("-")
        out.append((int(start), int(end or start)))
    return out


def _pdf_spec(value) -> tuple[str, str | None]:
    """"a.pdf" or {"source": "a.pdf", "pages": "7-184"}."""
    if isinstance(value, str):
        return value, None
    return value["source"], value.get("pages")


def load_case(path: Path) -> Case:
    data = json.loads(path.read_text(encoding="utf-8"))
    old_pdf, old_pages_spec = _pdf_spec(data["old_pdf"])
    new_pdf, new_pages_spec = _pdf_spec(data["new_pdf"])
    errors: list[str] = []
    items: list[TruthItem] = []
    for raw in data.get("items", []):
        item = TruthItem(
            id=raw["id"],
            summary=raw.get("summary", ""),
            change_type=raw["change_type"],
            old_pages=_pages(raw.get("old_pages")),
            new_pages=_pages(raw.get("new_pages")),
            old_anchors=tuple(a for a in raw.get("old_anchors", []) if a),
            new_anchors=tuple(a for a in raw.get("new_anchors", []) if a),
            expected_risk=raw["expected_risk"],
            scored=raw.get("scored", True),
            risk_rationale=raw.get("risk_rationale", ""),
            scored_note=raw.get("scored_note", ""),
            accept_change_types=tuple(raw.get("accept_change_types", [])),
        )
        if any(t not in CHANGE_TYPES for t in (item.change_type, *item.accept_change_types)):
            errors.append(f"{item.id}: change_type／accept_change_types 必須是 {'/'.join(CHANGE_TYPES)}")
        if item.expected_risk not in RISKS:
            errors.append(f"{item.id}: expected_risk 必須是 {'/'.join(RISKS)}")
        if not (item.old_anchors or item.new_anchors or item.old_pages or item.new_pages):
            errors.append(f"{item.id}: 至少要有一個 anchor 或頁碼，否則永遠對不到")
        items.append(item)
    ids = [i.id for i in items]
    if len(ids) != len(set(ids)):
        errors.append("答案 id 重複")
    if errors:
        raise ValueError(f"{path}：\n  " + "\n  ".join(errors))
    return Case(
        id=data["id"],
        title=data.get("title", data["id"]),
        old_pdf=old_pdf,
        new_pdf=new_pdf,
        items=tuple(items),
        old_pages_spec=old_pages_spec,
        new_pages_spec=new_pages_spec,
        page_tolerance=int(data.get("page_tolerance", 0)),
        old_version=data.get("old_version"),
        new_version=data.get("new_version"),
        ground_truth_source=data.get("ground_truth_source", ""),
        label_status=data.get("label_status", "draft"),
        labeled_by=data.get("labeled_by", ""),
        home_field=bool(data.get("home_field", False)),
        recall_only=bool(data.get("recall_only", False)),
        notes=data.get("notes", ""),
    )


# ── a tool's reported changes ────────────────────────────────────────────


@dataclass(frozen=True)
class Reported:
    row: int  # CSV line number, so a reviewer can find it
    item_id: str
    change_type: str | None
    old_page: int | None
    new_page: int | None
    old_text: str
    new_text: str
    risk: str | None
    gt_ids: tuple[str, ...] | None  # None → match automatically; () → a person marked it noise
    note: str = ""


def normalize_text(text: str) -> str:
    """Width/whitespace-insensitive: '80 °C' == '80°C', '，' == ','. Tools
    disagree on all of these and none of it is a content difference."""
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", text or "")).casefold()


def _parse_page(value: str) -> int | None:
    digits = re.search(r"\d+", value or "")
    return int(digits.group()) if digits else None


def _parse_choice(value: str, aliases: dict[str, str], what: str) -> str | None:
    value = (value or "").strip()
    if not value:
        return None
    resolved = aliases.get(value) or aliases.get(value.casefold())
    if resolved is None:
        raise ValueError(f"看不懂的{what}「{value}」")
    return resolved


def load_results(path: Path, case: Case) -> list[Reported]:
    known = {i.id for i in case.items}
    errors: list[str] = []
    rows: list[Reported] = []
    with path.open(encoding="utf-8-sig", newline="") as fh:  # utf-8-sig: Excel's "CSV UTF-8" adds a BOM
        reader = csv.DictReader(fh)
        missing = [c for c in ("old_text", "new_text") if c not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"{path}：缺少欄位 {missing}，請從 templates/result_template.csv 複製表頭")
        for line_no, raw in enumerate(reader, start=2):
            if not any((v or "").strip() for v in raw.values()):
                continue  # blank line
            try:
                change_type = _parse_choice(raw.get("change_type", ""), _CHANGE_TYPE_ALIASES, "變更類型")
                risk = _parse_choice(raw.get("risk", ""), _RISK_ALIASES, "風險等級")
            except ValueError as exc:
                errors.append(f"第 {line_no} 行：{exc}")
                continue
            gt_raw = (raw.get("gt_id") or "").strip()
            gt_ids: tuple[str, ...] | None
            if not gt_raw:
                gt_ids = None
            elif gt_raw.casefold() in _FORCED_NOISE:
                gt_ids = ()
            else:
                gt_ids = tuple(g.strip() for g in re.split(r"[;,、\s]+", gt_raw) if g.strip())
                unknown = [g for g in gt_ids if g not in known]
                if unknown:
                    errors.append(f"第 {line_no} 行：gt_id {unknown} 不在答案裡")
            rows.append(
                Reported(
                    row=line_no,
                    item_id=(raw.get("item_id") or "").strip() or f"#{line_no}",
                    change_type=change_type,
                    old_page=_parse_page(raw.get("old_page", "")),
                    new_page=_parse_page(raw.get("new_page", "")),
                    old_text=raw.get("old_text") or "",
                    new_text=raw.get("new_text") or "",
                    risk=risk,
                    gt_ids=gt_ids,
                    note=raw.get("note") or "",
                )
            )
    if errors:
        raise ValueError(f"{path}：\n  " + "\n  ".join(errors))
    return rows


# ── matching ─────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Match:
    gt_ids: tuple[str, ...]
    how: str  # 'auto' | 'manual'


def _page_compatible(page: int | None, truth_pages: tuple[int, ...], tolerance: int) -> bool:
    if page is None or not truth_pages:
        return True  # nothing to contradict
    return any(abs(page - p) <= tolerance for p in truth_pages)


def _page_hit(page: int | None, truth_pages: tuple[int, ...], tolerance: int) -> bool:
    return page is not None and bool(truth_pages) and _page_compatible(page, truth_pages, tolerance)


def auto_match(reported: Reported, case: Case) -> tuple[str, ...]:
    """Every answer-key item this row evidences. A row quoting a whole page
    can legitimately cover several items, so this isn't one-to-one."""
    old_text, new_text = normalize_text(reported.old_text), normalize_text(reported.new_text)
    tol = case.page_tolerance
    hits = []
    for item in case.items:
        if not (
            _page_compatible(reported.old_page, item.old_pages, tol)
            and _page_compatible(reported.new_page, item.new_pages, tol)
        ):
            continue
        if item.old_anchors or item.new_anchors:
            hit = any(normalize_text(a) in old_text for a in item.old_anchors) or any(
                normalize_text(a) in new_text for a in item.new_anchors
            )
        else:  # a location-only item (e.g. "clause 3.10 新增" from an official amendment table)
            hit = _page_hit(reported.old_page, item.old_pages, tol) or _page_hit(reported.new_page, item.new_pages, tol)
        if hit:
            hits.append(item.id)
    return tuple(hits)


def on_answer_pages(reported: Reported, case: Case) -> bool:
    """Could this unmatched row be a fragment of a scored item? When the
    answer key is incomplete (recall_only) an unmatched row isn't noise by
    default, but one sitting on an answer's pages is worth a person's look."""
    tol = case.page_tolerance
    return any(
        _page_hit(reported.old_page, i.old_pages, tol) or _page_hit(reported.new_page, i.new_pages, tol)
        for i in case.items
        if i.scored
    )


def match_all(reported: list[Reported], case: Case) -> list[Match]:
    return [
        Match(r.gt_ids, "manual") if r.gt_ids is not None else Match(auto_match(r, case), "auto") for r in reported
    ]


# ── scoring ──────────────────────────────────────────────────────────────


@dataclass
class ItemOutcome:
    item: TruthItem
    hits: list[Reported]
    tool_risk: str | None  # highest risk among the hits — the card a reviewer would notice
    type_ok: bool | None  # None = the tool reported no change type for it
    page_ok: bool | None  # None = the tool reported no page for it


@dataclass
class ToolScore:
    tool: str
    case_id: str
    reported: int
    scored_total: int
    detected: int
    high_total: int
    high_detected: int
    missed_high: list[str]
    noise: list[Reported]
    dont_care: int  # rows matching only an unscored item (e.g. a version header)
    on_scored: int  # rows matching at least one scored item
    risk_graded: bool
    risk_known: int
    risk_agree: int
    high_underrated: list[str]
    over_rated: list[str]
    type_known: int
    type_ok: int
    page_known: int
    page_ok: int
    manual: int
    recall_only: bool
    precision_base: int  # rows that count toward precision — 0 when the answer key is incomplete
    outcomes: list[ItemOutcome] = field(default_factory=list)


def _side_page_ok(hits: list[Reported], item: TruthItem) -> bool | None:
    checks = []
    for r in hits:
        if r.old_page is not None and item.old_pages:
            checks.append(r.old_page in item.old_pages)
        if r.new_page is not None and item.new_pages:
            checks.append(r.new_page in item.new_pages)
    return any(checks) if checks else None


def score_tool(tool: str, case: Case, reported: list[Reported], matches: list[Match]) -> ToolScore:
    scored_ids = {i.id for i in case.items if i.scored}
    hits_by_item: dict[str, list[Reported]] = {i.id: [] for i in case.items}
    for r, m in zip(reported, matches):
        for gid in m.gt_ids:
            hits_by_item[gid].append(r)

    outcomes = []
    for item in case.items:
        if not item.scored:
            continue
        hits = hits_by_item[item.id]
        risks = [r.risk for r in hits if r.risk]
        types = [r.change_type for r in hits if r.change_type]
        outcomes.append(
            ItemOutcome(
                item=item,
                hits=hits,
                tool_risk=max(risks, key=RISK_RANK.__getitem__) if risks else None,
                type_ok=any(t in item.accepted_types for t in types) if types else None,
                page_ok=_side_page_ok(hits, item) if hits else None,
            )
        )

    detected = [o for o in outcomes if o.hits]
    high = [o for o in outcomes if o.item.expected_risk == "High"]
    with_risk = [o for o in detected if o.tool_risk]
    return ToolScore(
        tool=tool,
        case_id=case.id,
        reported=len(reported),
        scored_total=len(outcomes),
        detected=len(detected),
        high_total=len(high),
        high_detected=sum(1 for o in high if o.hits),
        missed_high=[o.item.id for o in high if not o.hits],
        noise=[r for r, m in zip(reported, matches) if not m.gt_ids],
        dont_care=sum(1 for m in matches if m.gt_ids and not scored_ids.intersection(m.gt_ids)),
        on_scored=sum(1 for m in matches if scored_ids.intersection(m.gt_ids)),
        risk_graded=any(r.risk for r in reported),
        risk_known=len(with_risk),
        risk_agree=sum(1 for o in with_risk if o.tool_risk == o.item.expected_risk),
        high_underrated=[o.item.id for o in with_risk if o.item.expected_risk == "High" and o.tool_risk != "High"],
        over_rated=[o.item.id for o in with_risk if RISK_RANK[o.tool_risk] > RISK_RANK[o.item.expected_risk]],
        type_known=sum(1 for o in detected if o.type_ok is not None),
        type_ok=sum(1 for o in detected if o.type_ok),
        page_known=sum(1 for o in detected if o.page_ok is not None),
        page_ok=sum(1 for o in detected if o.page_ok),
        manual=sum(1 for m in matches if m.how == "manual"),
        recall_only=case.recall_only,
        precision_base=0 if case.recall_only else len(reported),
        outcomes=outcomes,
    )


_SUMMED = (
    "reported", "scored_total", "detected", "high_total", "high_detected", "dont_care", "on_scored",
    "risk_known", "risk_agree", "type_known", "type_ok", "page_known", "page_ok", "manual", "precision_base",
)


def combine(scores: list[ToolScore]) -> ToolScore:
    """Micro-average one tool across cases: sum the counts, then divide —
    a 2-item case doesn't weigh as much as a 40-item one. Precision only
    covers cases with a complete answer key (recall_only=False)."""
    total = ToolScore(
        tool=scores[0].tool, case_id="*", missed_high=[], noise=[], high_underrated=[], over_rated=[],
        risk_graded=any(s.risk_graded for s in scores), recall_only=all(s.recall_only for s in scores),
        **{k: 0 for k in _SUMMED},
    )
    for s in scores:
        for k in _SUMMED:
            setattr(total, k, getattr(total, k) + getattr(s, k))
        total.missed_high += [f"{s.case_id}:{i}" for i in s.missed_high]
        total.high_underrated += [f"{s.case_id}:{i}" for i in s.high_underrated]
        total.over_rated += [f"{s.case_id}:{i}" for i in s.over_rated]
        if not s.recall_only:
            total.noise += s.noise
    return total


def precision(s: ToolScore) -> float | None:
    if not s.precision_base:
        return None
    return (s.precision_base - len(s.noise)) / s.precision_base


def _ratio(num: int, den: int) -> float | None:
    return num / den if den else None


# ── discovering cases and results ────────────────────────────────────────


def discover(root: Path, only: list[str] | None) -> list[Case]:
    cases = [load_case(p) for p in sorted((root / "cases").glob("*/case.json"))]
    if only:
        missing = set(only) - {c.id for c in cases}
        if missing:
            raise SystemExit(f"找不到案例：{sorted(missing)}")
        cases = [c for c in cases if c.id in only]
    return cases


def result_files(root: Path, case: Case) -> list[tuple[str, Path]]:
    files = sorted((root / "results" / case.id).glob("*.csv"))
    tools = [(p.stem, p) for p in files]
    return sorted(tools, key=lambda t: (t[0] != OURS, t[0]))


def _materialize(source: str, spec: str | None, build_dir: Path) -> Path:
    """The PDF a tool is actually given. With a page spec, that's an extract
    built under <root>/build/ (gitignored — it's a copy of the source), and
    every page number in the answer key counts pages of the extract."""
    src = REPO_ROOT / source
    if spec is None:
        return src
    target = build_dir / f"{src.stem}_p{spec.replace(',', '_')}.pdf"
    if target.exists() and target.stat().st_mtime >= src.stat().st_mtime:
        return target
    import fitz  # PyMuPDF, same as backend/services/extraction.py

    out = fitz.open()
    with fitz.open(src) as doc:
        for start, end in _page_ranges(spec):
            out.insert_pdf(doc, from_page=start - 1, to_page=end - 1)
    target.parent.mkdir(parents=True, exist_ok=True)
    out.save(target, garbage=3, deflate=True)
    return target


def case_pdfs(case: Case, root: Path) -> tuple[Path, Path]:
    build_dir = root / "build" / case.id
    return (
        _materialize(case.old_pdf, case.old_pages_spec, build_dir),
        _materialize(case.new_pdf, case.new_pages_spec, build_dir),
    )


def describe_pdf(path: str, spec: str | None) -> str:
    return f"{path}（第 {spec} 頁）" if spec else path


def load_meta(csv_path: Path) -> dict:
    meta_path = csv_path.with_suffix(".json")
    return json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}


def not_run_yet(reported: list[Reported], meta: dict) -> bool:
    """A fresh scaffold, not a tool that found nothing: no rows AND no real
    run date. A tool that genuinely reported zero changes still gets scored
    (as missing everything) once its run_date is filled in."""
    return not reported and not re.match(r"\d{4}-\d{2}-\d{2}", str(meta.get("run_date") or ""))


