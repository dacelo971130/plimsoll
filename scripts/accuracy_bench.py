def _git_version() -> str:
    def git(*args: str) -> str:
        return subprocess.run(["git", *args], cwd=REPO_ROOT, capture_output=True, text=True).stdout.strip()

    sha = git("rev-parse", "--short", "HEAD") or "unknown"
    dirty = git("status", "--porcelain", "--", "backend", "data/store/config")
    return f"{sha}{'-dirty' if dirty else ''}"


def plimsoll_rows(differences: list[dict]) -> list[dict]:
    rows = []
    for d in differences:
        old, new = d.get("old") or {}, d.get("new") or {}
        rows.append(
            {
                "item_id": d["id"],
                "change_type": d["change_type"],
                "old_page": (old.get("page") or {}).get("pdf_page") or "",
                "new_page": (new.get("page") or {}).get("pdf_page") or "",
                "old_text": old.get("text") or "",
                "new_text": new.get("text") or "",
                "risk": d.get("ai_risk") or "",
                "gt_id": "",
                "note": d.get("rule_id") or d.get("kind") or "",
            }
        )
    return rows


def carry_over_adjudication(rows: list[dict], previous: Path) -> int:
    """A person's `gt_id` on an earlier run survives a re-run for the very
    same (old_text, new_text) row; anything the engine now reports
    differently has to be judged again. Returns how many were kept."""
    if not previous.exists():
        return 0
    with previous.open(encoding="utf-8-sig", newline="") as fh:
        judged = {
            (r.get("old_text") or "", r.get("new_text") or ""): r["gt_id"]
            for r in csv.DictReader(fh)
            if (r.get("gt_id") or "").strip()
        }
    kept = 0
    for row in rows:
        gt = judged.get((row["old_text"], row["new_text"]))
        if gt:
            row["gt_id"] = gt
            kept += 1
    return kept


