"""Accuracy benchmark: score Plimsoll and competitor tools on the same
documents against the same hand-written answer key.

Every tool — ours included — is scored from one CSV shape
(data/benchmark/templates/result_template.csv), so the engine gets no
special path through the scorer. Plimsoll's CSV is generated by
`run-plimsoll`; a competitor's is transcribed by whoever ran it (most
commercial compare tools have no API, and uploading a document to a cloud
tool is a decision for a person, not this script).

Matching a reported change to an answer-key item is deliberately dumb and
inspectable: the reported old/new text must contain one of the item's
anchors (specific strings such as "80°C" or "CP-120"), and any page the
tool reports must sit within the case's page tolerance. Tools that split a
sentence into word-level fragments will leave some rows unmatched — those
are listed in the report, and a person can settle them by filling `gt_id`.
The same manual override is available for every tool, ours included.

No model is called: `run-plimsoll` strips LLM keys from its own environment
(the deterministic rules_first path is what's measured) unless --allow-llm.

    python3 scripts/accuracy_bench.py run-plimsoll
    python3 scripts/accuracy_bench.py prepare        # the exact PDFs to give every other tool
    python3 scripts/accuracy_bench.py scaffold --tool acrobat
    python3 scripts/accuracy_bench.py score
    python3 scripts/accuracy_bench.py score --root data/benchmark-local
"""

